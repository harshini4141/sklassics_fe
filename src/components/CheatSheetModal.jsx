import { useState, useEffect } from 'react'

export function CheatSheetModal({ sheet, onClose, onBookDemo }) {
  const [copiedIndex, setCopiedIndex] = useState(null)
  const [searchQuery, setSearchQuery] = useState('')
  const [downloadSuccess, setDownloadSuccess] = useState(false)

  useEffect(() => {
    const handleKeyDown = (e) => {
      if (e.key === 'Escape') onClose()
    }
    window.addEventListener('keydown', handleKeyDown)
    document.body.style.overflow = 'hidden'
    return () => {
      window.removeEventListener('keydown', handleKeyDown)
      document.body.style.overflow = ''
    }
  }, [onClose])

  if (!sheet) return null

  const handleCopy = (code, index) => {
    navigator.clipboard.writeText(code)
    setCopiedIndex(index)
    setTimeout(() => setCopiedIndex(null), 2000)
  }

  const handleDownload = () => {
    // Generate downloadable text/markdown file of the cheat sheet
    const content = `# ${sheet.title}\nCategory: ${sheet.category}\n${sheet.description}\n\n` +
      sheet.sections.map((s) => `## ${s.heading}\n${s.explanation}\n\n\`\`\`\n${s.code}\n\`\`\`\n`).join('\n') +
      `\n\nGenerated by Sklassics Technologies - Learn. Build. Grow. (https://sklassics.in)`

    const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const link = document.createElement('a')
    link.href = url
    link.download = `${sheet.id}.md`
    document.body.appendChild(link)
    link.click()
    document.body.removeChild(link)
    URL.revokeObjectURL(url)

    setDownloadSuccess(true)
    setTimeout(() => setDownloadSuccess(false), 3000)
  }

  const filteredSections = sheet.sections.filter((s) => {
    if (!searchQuery.trim()) return true
    const q = searchQuery.toLowerCase()
    return s.heading.toLowerCase().includes(q) ||
      s.explanation.toLowerCase().includes(q) ||
      s.code.toLowerCase().includes(q)
  })

  return (
    <div
      className="modal-backdrop"
      onClick={onClose}
      role="dialog"
      aria-modal="true"
      aria-labelledby="cheatsheet-modal-title"
    >
      <div
        className="modal-container cheatsheet-modal-container"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Modal Header */}
        <div className="cheatsheet-modal-header">
          <div className="cheatsheet-header-left">
            <span className="cheatsheet-modal-tag">
              <span>{sheet.icon}</span>
              <span>{sheet.category}</span>
            </span>
            <h2 id="cheatsheet-modal-title">{sheet.title}</h2>
            <p>{sheet.description}</p>
          </div>
          <button
            type="button"
            className="modal-close-btn"
            onClick={onClose}
            aria-label="Close Cheatsheet"
          >
            ✕
          </button>
        </div>

        {/* Action Controls Strip */}
        <div className="cheatsheet-controls-bar">
          <div className="cheatsheet-search-box">
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <circle cx="11" cy="11" r="8" />
              <line x1="21" y1="21" x2="16.65" y2="16.65" />
            </svg>
            <input
              type="text"
              placeholder="Search code snippets or topics..."
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              className="cheatsheet-search-input"
            />
            {searchQuery && (
              <button
                type="button"
                className="cheatsheet-search-clear"
                onClick={() => setSearchQuery('')}
              >
                ✕
              </button>
            )}
          </div>

          <div className="cheatsheet-btn-group">
            <button
              type="button"
              className="cheatsheet-download-btn"
              onClick={handleDownload}
            >
              <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4" />
                <polyline points="7 10 12 15 17 10" />
                <line x1="12" y1="15" x2="12" y2="3" />
              </svg>
              <span>{downloadSuccess ? 'Downloaded!' : 'Download Guide (.md)'}</span>
            </button>

            <button
              type="button"
              className="cheatsheet-mentor-btn"
              onClick={() => {
                onClose()
                if (onBookDemo) onBookDemo()
              }}
            >
              <span>Ask a Mentor</span>
            </button>
          </div>
        </div>

        {/* Modal Code & Sections Body */}
        <div className="cheatsheet-modal-body">
          {filteredSections.length === 0 ? (
            <div className="cheatsheet-empty-search">
              <p>No queries or topics match "{searchQuery}".</p>
              <button type="button" onClick={() => setSearchQuery('')}>Clear search</button>
            </div>
          ) : (
            filteredSections.map((section, idx) => (
              <div key={section.heading} className="cheatsheet-snippet-card">
                <div className="snippet-card-top">
                  <div>
                    <h3 className="snippet-heading">{section.heading}</h3>
                    <p className="snippet-explanation">{section.explanation}</p>
                  </div>
                  <button
                    type="button"
                    className="snippet-copy-btn"
                    onClick={() => handleCopy(section.code, idx)}
                  >
                    {copiedIndex === idx ? (
                      <>
                        <span style={{ color: '#10b981' }}>✓ Copied</span>
                      </>
                    ) : (
                      <>
                        <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                          <rect x="9" y="9" width="13" height="13" rx="2" ry="2" />
                          <path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1" />
                        </svg>
                        <span>Copy Code</span>
                      </>
                    )}
                  </button>
                </div>

                <div className="snippet-code-wrapper">
                  <pre className="snippet-pre">
                    <code>{section.code}</code>
                  </pre>
                </div>
              </div>
            ))
          )}
        </div>

        {/* Footer info strip */}
        <div className="cheatsheet-modal-footer">
          <span>{sheet.downloads} · Verified for top tech interviews</span>
          <a
            href="tel:+919392732581"
            className="cheatsheet-footer-link"
          >
            Need help preparing? Call admissions: +91 93927 32581
          </a>
        </div>
      </div>
    </div>
  )
}
